"""
PyMBAL - Material Balance Engine

Combines underground withdrawal and reservoir expansion
terms to perform black-oil material balance calculations.

General Havlena-Ode formulation:

    F = N(Eo + mEg + Efw) + We

Define:

    E = Eo + mEg + Efw

Therefore:

    F - We = N E

For a volumetric reservoir:

    We = 0

and:

    F = N E

The slope of a plot of:

    (F - We) vs E

gives the original oil in place (N).
"""

import numpy as np
import pandas as pd

from src.core.underground_withdrawal import (
    calculate_underground_withdrawal,
)

from src.core.expansion import (
    calculate_total_expansion,
)


class MaterialBalanceEngine:
    """
    Main material balance calculation engine.

    The engine combines:

        Underground withdrawal
        +
        Reservoir expansion
        +
        Water influx

    to solve the material balance equation.
    """

    # ========================================================
    # Initialization
    # ========================================================

    def __init__(self, reservoir_state):

        self.state = reservoir_state

    # ========================================================
    # Validate Input
    # ========================================================

    @staticmethod
    def _validate_input(df):

        required_columns = [
            "Pressure_psia",
            "Np_STB",
            "Gp_Mscf",
            "Wp_STB",
            "Bo_rb_per_STB",
            "Bg_rb_per_scf",
            "Bw_rb_per_STB",
            "Rs_scf_per_STB",
        ]

        missing = [
            column
            for column in required_columns
            if column not in df.columns
        ]

        if missing:

            raise ValueError(
                "Missing columns required for "
                f"material balance: {missing}"
            )

        if df.empty:

            raise ValueError(
                "Material balance dataset is empty."
            )

    # ========================================================
    # Water Influx
    # ========================================================

    @staticmethod
    def _get_water_influx(df):

        """
        Retrieve water influx from the dataframe.

        If no aquifer model has been implemented yet,
        We is assumed to be zero.

        The column:

            We_rb

        can later be generated by the aquifer engine.
        """

        if "We_rb" in df.columns:

            We = df["We_rb"].astype(float)

            if (We < 0).any():

                raise ValueError(
                    "Water influx We cannot be negative."
                )

            return We

        return pd.Series(
            0.0,
            index=df.index,
            name="We_rb",
        )

    # ========================================================
    # Calculate MBE Terms
    # ========================================================

    def calculate_terms(self, df):

        """
        Calculate all material balance terms.

        Returns
        -------
        pandas.DataFrame
            Original dataframe plus:

                F_rb

                Eo_rb_per_STB
                Eg_rb_per_STB
                Efw_rb_per_STB
                mEg_rb_per_STB
                Etotal_rb_per_STB

                We_rb
                F_minus_We_rb

                N_apparent_STB
        """

        self._validate_input(df)

        result = df.copy()

        # ----------------------------------------------------
        # Underground withdrawal
        #
        # Recalculate F from the current PVT + production history.
        # This keeps the MBE engine self-contained and prevents it
        # from trusting a stale/precomputed F column.
        # ----------------------------------------------------

        result = calculate_underground_withdrawal(
            result
        )

        print("\nDEBUG - AFTER UNDERGROUND WITHDRAWAL")
        print("=" * 70)

        debug_columns = [
            "Pressure_psia",
            "F_rb",
        ]

        if len(result) > 1:
            print(
                result[debug_columns].iloc[1:4]
            )

        # ----------------------------------------------------
        # Expansion terms
        # ----------------------------------------------------

        result = calculate_total_expansion(

            result,

            Boi=self.state.Boi_rb_per_STB,

            Bgi=self.state.Bgi_rb_per_scf,

            Rsi=self.state.Rsi_scf_per_STB,

            Pi=self.state.initial_pressure_psia,

            Swi=self.state.initial_water_saturation,

            cf=self.state.formation_compressibility_psi_inv,

            cw=self.state.water_compressibility_psi_inv,

            m=self.state.gas_cap_ratio,
        )


        # ----------------------------------------------------
        # Water influx
        # ----------------------------------------------------

        result["We_rb"] = (
            self._get_water_influx(result)
        )

        # ----------------------------------------------------
        # Debug after all primary MBE terms are available
        # ----------------------------------------------------

        print("\nDEBUG - AFTER EXPANSION / WATER INFLUX")
        print("=" * 70)

        if len(result) > 1:
            print(
                result[
                    [
                        "Pressure_psia",
                        "F_rb",
                        "We_rb",
                        "Etotal_rb_per_STB",
                    ]
                ].iloc[1:4]
            )

        debug_n = (
            result["F_rb"] - result["We_rb"]
        ) / result["Etotal_rb_per_STB"]

        print("\nDEBUG - N FROM ENGINE TERMS")
        print(debug_n.iloc[1:4])

        # ----------------------------------------------------
        # Net underground withdrawal
        #
        # F - We
        # ----------------------------------------------------

        result["F_minus_We_rb"] = (
            result["F_rb"]
            -
            result["We_rb"]
        )

        # ----------------------------------------------------
        # Apparent OOIP
        #
        # N = (F - We) / E
        #
        # Undefined at initial condition because E = 0.
        # ----------------------------------------------------

        E = result[
            "Etotal_rb_per_STB"
        ]

        result[
            "N_apparent_STB"
        ] = np.where(
            np.abs(E) > 1e-12,
            result["F_minus_We_rb"] / E,
            np.nan,
        )

        return result

    # ========================================================
    # Havlena-Ode Regression
    # ========================================================

    @staticmethod
    def estimate_ooip(df):

        """
        Estimate OOIP using Havlena-Ode regression.

        Equation:

            F - We = N E

        Therefore, regression through the origin gives:

            slope = N

        Parameters
        ----------
        df : pandas.DataFrame

        Returns
        -------
        dict

            N_STB
            R_squared
            intercept
            slope
            residual_sum
        """

        required = [
            "F_minus_We_rb",
            "Etotal_rb_per_STB",
        ]

        missing = [
            column
            for column in required
            if column not in df.columns
        ]

        if missing:

            raise ValueError(
                "Missing columns required for "
                f"Havlena-Ode regression: {missing}"
            )

        x = df[
            "Etotal_rb_per_STB"
        ].to_numpy(
            dtype=float
        )

        y = df[
            "F_minus_We_rb"
        ].to_numpy(
            dtype=float
        )

        # ----------------------------------------------------
        # Remove initial zero-expansion point
        # ----------------------------------------------------

        valid = (
            np.isfinite(x)
            &
            np.isfinite(y)
            &
            (np.abs(x) > 1e-12)
        )

        x_valid = x[valid]
        y_valid = y[valid]

        if len(x_valid) < 2:

            raise ValueError(
                "Insufficient valid data points for "
                "Havlena-Ode regression."
            )

        # ----------------------------------------------------
        # Regression THROUGH ORIGIN
        #
        # y = N*x
        #
        # N = sum(x*y) / sum(x^2)
        # ----------------------------------------------------

        denominator = np.sum(
            x_valid ** 2
        )

        if denominator <= 0:

            raise ValueError(
                "Expansion data does not contain "
                "sufficient variation."
            )

        N = (
            np.sum(
                x_valid * y_valid
            )
            /
            denominator
        )

        # ----------------------------------------------------
        # Predicted values
        # ----------------------------------------------------

        y_pred = (
            N * x_valid
        )

        residuals = (
            y_valid
            -
            y_pred
        )

        # ----------------------------------------------------
        # R² for through-origin regression
        #
        # Use uncentered total sum of squares because
        # the physical MBE relationship is constrained
        # to pass through the origin.
        # ----------------------------------------------------

        ss_res = np.sum(
            residuals ** 2
        )

        ss_tot = np.sum(
            y_valid ** 2
        )

        if ss_tot > 0:

            r_squared = (
                1.0
                -
                ss_res / ss_tot
            )

        else:

            r_squared = np.nan

        return {

            "N_STB": float(N),

            "R_squared": float(
                r_squared
            ),

            "intercept": 0.0,

            "slope": float(N),

            "residual_sum": float(
                np.sum(
                    np.abs(residuals)
                )
            ),

            "data_points": int(
                len(x_valid)
            ),
        }

    # ========================================================
    # Full Material Balance Analysis
    # ========================================================

    def analyze(self, df):

        """
        Perform the complete Version-1 material balance
        calculation.

        Returns
        -------
        tuple

            result_df
            analysis
        """

        result = self.calculate_terms(
            df
        )

        analysis = self.estimate_ooip(
            result
        )

        N = analysis[
            "N_STB"
        ]

        # ----------------------------------------------------
        # Regression-predicted withdrawal
        # ----------------------------------------------------

        result[
            "F_minus_We_predicted_rb"
        ] = (
            N
            *
            result[
                "Etotal_rb_per_STB"
            ]
        )

        # ----------------------------------------------------
        # Material balance residual
        # ----------------------------------------------------

        result[
            "MBE_residual_rb"
        ] = (
            result[
                "F_minus_We_rb"
            ]
            -
            result[
                "F_minus_We_predicted_rb"
            ]
        )

        return result, analysis

    # ========================================================
    # Display Summary
    # ========================================================

    @staticmethod
    def display_summary(
        analysis
    ):

        print("\n")

        print("=" * 65)
        print(
            "MATERIAL BALANCE ANALYSIS"
        )
        print("=" * 65)

        print(
            "\nHavlena-Ode Regression"
        )

        print("-" * 65)

        print(
            f"Estimated OOIP (N) : "
            f"{analysis['N_STB']:,.2f} STB"
        )

        print(
            f"Estimated OOIP      : "
            f"{analysis['N_STB'] / 1e6:.4f} MMSTB"
        )

        print(
            f"R²                  : "
            f"{analysis['R_squared']:.6f}"
        )

        print(
            f"Regression slope    : "
            f"{analysis['slope']:.6f}"
        )

        print(
            f"Data points         : "
            f"{analysis['data_points']}"
        )

        print(
            f"Residual sum        : "
            f"{analysis['residual_sum']:.4f} rb"
        )

        print("-" * 65)

        print(
            "\n✓ Material balance analysis completed."
        )